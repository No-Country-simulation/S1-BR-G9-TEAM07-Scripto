const dictionaries: Record<Lang, Record<string, string>> = { "pt-BR": ptBR, en };

type I18nContextValue = {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: TranslationKey, fallback?: string) => string;
};

const I18nContext = createContext<I18nContextValue>({
  lang: "pt-BR",
  setLang: () => undefined,
  t: (key, fallback) => fallback ?? key,
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>("pt-BR");

  useEffect(() => {
    const stored = typeof window !== "undefined" ? localStorage.getItem("scripto-lang") : null;
    if (stored === "pt-BR" || stored === "en") setLang(stored);
  }, []);

  useEffect(() => {
    if (typeof window === "undefined") return;
    localStorage.setItem("scripto-lang", lang);
    document.documentElement.lang = lang;
  }, [lang]);

  const value = useMemo<I18nContextValue>(
    () => ({
      lang,
      setLang,
      t: (key, fallback) => dictionaries[lang][key] ?? dictionaries["pt-BR"][key] ?? fallback ?? key,
    }),
    [lang],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
